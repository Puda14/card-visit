import { chromium } from "@playwright/test";
import { mkdir, copyFile } from "node:fs/promises";

await mkdir("qa/aperture-video", { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, recordVideo: { dir: "qa/aperture-video", size: { width: 1440, height: 1000 } } });
const page = await context.newPage();
page.on("pageerror", error => console.log("PAGE ERROR:", error.message));
page.on("console", message => { if (message.type() === "error") console.log("CONSOLE:", message.text()); });
await page.goto("http://127.0.0.1:3000/en", { waitUntil: "domcontentloaded" });
await page.getByTestId("intro").waitFor();
await page.screenshot({ path: "qa/aperture-initial.png" });
await page.waitForTimeout(600);
await page.screenshot({ path: "qa/intro.png" });
await page.waitForTimeout(550);
await page.screenshot({ path: "qa/aperture-mid.png" });
await page.waitForTimeout(500);
await page.screenshot({ path: "qa/intro-opening.png" });
await page.waitForTimeout(1000);
await page.screenshot({ path: "qa/swirl-reversing.png" });
await page.waitForTimeout(650);
await page.screenshot({ path: "qa/swirl-outward.png" });
await page.getByTestId("intro").waitFor({ state: "detached" });
await page.screenshot({ path: "qa/desktop.png", fullPage: true });
await context.close();
await copyFile(await page.video().path(), "qa/aperture-preview.webm");

const mobile = await browser.newContext({ viewport: { width: 390, height: 844 } });
const phone = await mobile.newPage();
await phone.goto("http://127.0.0.1:3000/en", { waitUntil: "domcontentloaded" });
await phone.getByTestId("intro").waitFor();
await phone.waitForTimeout(1000);
await phone.screenshot({ path: "qa/intro-mobile.png" });
await phone.getByTestId("intro").waitFor({ state: "detached" });
await phone.screenshot({ path: "qa/mobile.png", fullPage: true });
await phone.goto("http://127.0.0.1:3000/ja");
await phone.screenshot({ path: "qa/mobile-ja.png", fullPage: true });
await browser.close();
console.log("Saved aperture frame sequence and qa/aperture-preview.webm");
